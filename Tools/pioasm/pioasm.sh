# Regenerate a PIO header from its .pio source, or check that the header
# matches a fresh assembly.
#
#   pioasm.sh <dshot|uart|osd>           write the header
#   pioasm.sh <dshot|uart|osd> --check   exit non-zero when the header is not up to date
#
# dshot and uart: <name>.pio and <name>.pio.h in this directory.
# osd: osd_tx.pio and osd_tx.pio.h in platforms/nuttx/src/px4/rpi/rp2350/pio_osd.
#
# Needs pioasm 2.2.0 (pico-sdk 2.2.0, tools/pioasm). Set PIOASM to its path
# when it is not on PATH.

set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")"

PIOASM=${PIOASM:-pioasm}
PIOASM_VERSION=2.2.0
UPSTREAM_COMMIT=e45dae01b13a8bd61d9098f4c8b55d43b6cd9f53

Help() {

	echo "Usage: "
	echo "pioasm.sh <dshot|uart|osd> [--check]"
	echo " "
	exit 2
}

if [ "$#" -lt 1 ] || [ "$#" -gt 2 ]; then
	Help
fi

CHECK=0

if [ "$#" -eq 2 ]; then
	if [ "$2" != "--check" ]; then
		Help
	fi

	CHECK=1
fi

if ! "$PIOASM" --version 2>/dev/null | grep -q "$PIOASM_VERSION"; then
	echo "pioasm.sh: pioasm $PIOASM_VERSION is necessary (found: $("$PIOASM" --version 2>&1 || true))" >&2
	exit 2
else
	case $1 in
		"uart")
			FILEN=$1
			SRC=$FILEN.pio
			;;
		"dshot")
			FILEN=$1
			SRC=$FILEN.pio
			;;
		"osd")
			FILEN=$1
			SRC=../../platforms/nuttx/src/px4/rpi/rp2350/pio_osd/osd_tx.pio
			;;
		*) echo >&2 "Invalid option: $1"; Help; exit 1;;
	esac
fi

HEADER=$SRC.h

notice_osd() {
	cat <<NOTICE
/*
 * osd_tx PIO programs for the PX4 RP2350 analog OSD (pio_osd.c).
 *
 * Generated by pioasm $PIOASM_VERSION from osd_tx.pio, then reduced by
 * Tools/pioasm/pioasm.sh to the defines and the instruction arrays. Do not
 * edit. Regenerate with "Tools/pioasm/pioasm.sh osd".
 *
 * From Betaflight, src/platform/PICO/osd/osd_tx.pio.
 *
 * Copyright (c) Betaflight contributors.
 * Written by Matthew Selby.
 *
 * This program is free software: you can redistribute it and/or modify it
 * under the terms of the GNU General Public License as published by the
 * Free Software Foundation, either version 3 of the License, or (at your
 * option) any later version.
 *
 * This program is distributed in the hope that it will be useful, but WITHOUT
 * ANY WARRANTY; without even the implied warranty of MERCHANTABILITY or
 * FITNESS FOR A PARTICULAR PURPOSE. See the GNU General Public License for
 * more details.
 *
 * You should have received a copy of the GNU General Public License along
 * with this program. If not, see <http://www.gnu.org/licenses/>.
 */

NOTICE
}

generate() {
	local out=$1
	local body
	body=$(mktemp "${TMPDIR:-/tmp}/$FILEN.pio.h.XXXXXX")

	# Keep the defines and the instruction arrays only. The pico-sdk helper
	# code (inside "#if !PICO_NO_HARDWARE") is not used by PX4. Indent with
	# a tab so that the result agrees with the PX4 code style check.
	"$PIOASM" -o c-sdk "$SRC" /dev/stdout | awk '
		/^#if !PICO_NO_HARDWARE/ { skip = 1; depth = 0; next }
		skip && /^#if/           { depth++; next }
		skip && /^#endif/        { if (depth == 0) { skip = 0 } else { depth-- } next }
		skip                     { next }
		                         { sub(/^ +/, "\t"); print }
	' | cat -s > "$body"

	if [ "$FILEN" = "osd" ]; then
		{
			notice_osd
			cat "$body"
		} > "$out"
		rm -f "$body"
		return
	fi

	{
		cat <<NOTICE
/*
 * uart PIO programs for the PX4 RP2350 UART backend.
 *
 * Generated by pioasm $PIOASM_VERSION from uart.pio, then reduced by pioasm.sh
 * to the defines and the instruction arrays. Do not edit. Regenerate with
 * pioasm.sh.
 *
 * From ArduPilot, libraries/AP_HAL_ChibiOS/rp2350/pio/uart.pio, at
 * https://github.com/davidbuzz/ardupilot commit
 * $UPSTREAM_COMMIT, which took it from Betaflight,
 * src/platform/PICO/uart.pio. See uart.pio for the local modifications.
 *
 * Copyright (c) Betaflight contributors.
 * Written by Matthew Selby, with later work by Andy Piper and qqqlab.
 *
 * This program is free software: you can redistribute it and/or modify it
 * under the terms of the GNU General Public License as published by the
 * Free Software Foundation, either version 3 of the License, or (at your
 * option) any later version.
 *
 * This program is distributed in the hope that it will be useful, but WITHOUT
 * ANY WARRANTY; without even the implied warranty of MERCHANTABILITY or
 * FITNESS FOR A PARTICULAR PURPOSE. See the GNU General Public License for
 * more details.
 *
 * You should have received a copy of the GNU General Public License along
 * with this program. If not, see <http://www.gnu.org/licenses/>.
 */

NOTICE
		cat "$body"
	} > "$out"

	rm -f "$body"
}

if [ "$CHECK" -eq 1 ]; then
	fresh=$(mktemp "${TMPDIR:-/tmp}/$FILEN.h.check.XXXXXX")
	trap 'rm -f "$fresh"' EXIT
	generate "$fresh"
	diff -u "$HEADER" "$fresh"

else
	generate "$HEADER"
fi
