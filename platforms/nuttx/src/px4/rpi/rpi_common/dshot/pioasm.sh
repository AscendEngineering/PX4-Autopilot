# Regenerate dshot.pio.h from dshot.pio, or check that the committed header
# matches a fresh assembly.
#
#   pioasm.sh           write dshot.pio.h
#   pioasm.sh --check   exit non-zero when dshot.pio.h is not up to date
#
# Needs pioasm 2.2.0 (pico-sdk 2.2.0, tools/pioasm). Set PIOASM to its path
# when it is not on PATH.

set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")"

PIOASM=${PIOASM:-pioasm}
PIOASM_VERSION=2.2.0
UPSTREAM_COMMIT=e45dae01b13a8bd61d9098f4c8b55d43b6cd9f53

if ! "$PIOASM" --version 2>/dev/null | grep -q "$PIOASM_VERSION"; then
	echo "pioasm.sh: pioasm $PIOASM_VERSION is necessary (found: $("$PIOASM" --version 2>&1 || true))" >&2
	exit 2
fi

generate() {
	local out=$1
	local body
	body=$(mktemp "${TMPDIR:-/tmp}/dshot.pio.h.XXXXXX")

	# Keep the defines and the instruction arrays only. The pico-sdk helper
	# code (inside "#if !PICO_NO_HARDWARE") is not used by PX4. Indent with
	# a tab so that the result agrees with the PX4 code style check.
	"$PIOASM" -o c-sdk dshot.pio /dev/stdout | awk '
		/^#if !PICO_NO_HARDWARE/ { skip = 1; depth = 0; next }
		skip && /^#if/           { depth++; next }
		skip && /^#endif/        { if (depth == 0) { skip = 0 } else { depth-- } next }
		skip                     { next }
		                         { sub(/^ +/, "\t"); print }
	' | cat -s > "$body"

	{
		cat <<NOTICE
/*
 * DShot PIO programs for the PX4 RP2350 DShot backend.
 *
 * Generated by pioasm $PIOASM_VERSION from dshot.pio, then reduced by pioasm.sh
 * to the defines and the instruction arrays. Do not edit. Regenerate with
 * pioasm.sh.
 *
 * From ArduPilot, libraries/AP_HAL_ChibiOS/rp2350/pio/dshot.pio, at
 * https://github.com/davidbuzz/ardupilot commit
 * $UPSTREAM_COMMIT, which took it from Betaflight,
 * src/platform/PICO/dshot.pio. See dshot.pio for the local modifications.
 *
 * Copyright (c) Betaflight contributors.
 * Written by Matthew Selby, with later work by Andy Piper and qqqlab.
 *
 * This program is free software: you can redistribute it and/or modify it
 * under the terms of the GNU General Public License as published by the
 * Free Software Foundation, either version 3 of the License, or (at your
 * option) any later version.
 *
 * This program is distributed in the hope that it will be useful, but WITHOUT
 * ANY WARRANTY; without even the implied warranty of MERCHANTABILITY or
 * FITNESS FOR A PARTICULAR PURPOSE. See the GNU General Public License for
 * more details.
 *
 * You should have received a copy of the GNU General Public License along
 * with this program. If not, see <http://www.gnu.org/licenses/>.
 */

NOTICE
		cat "$body"
	} > "$out"

	rm -f "$body"
}

if [ "${1:-}" = "--check" ]; then
	fresh=$(mktemp "${TMPDIR:-/tmp}/dshot.pio.h.check.XXXXXX")
	trap 'rm -f "$fresh"' EXIT
	generate "$fresh"
	diff -u dshot.pio.h "$fresh"

else
	generate dshot.pio.h
fi
